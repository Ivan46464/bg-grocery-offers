def _has(name: str, words: list[str]) -> bool:
    return any(w in name for w in words)


def derive_tags(product_name: str) -> list[str]:
    n = " " + product_name.lower() + " "
    tags: list[str] = []

    dairy = _has(n, DAIRY)
    meat = _has(n, MEAT) and not _has(n, ["безмесн", "вегетар", "веган", "соев", "растителн"])
    household = _has(n, HOUSEHOLD) and not dairy and not meat
    if household:
        tags.append("домакинство")
    if dairy:
        tags.append("млечни")
    if meat:
        tags.append("месо")
    if _has(n, [" био ", " bio ", "organic", "органик", "еко "]) and not household:
        tags.append("био")
    # Lent: explicitly labelled, or a plant staple that is not an animal product and not
    # pastry/confectionery (those almost always contain egg, milk or butter).
    explicit_lent = _has(n, ["постн", "веган", "vegan"])
    pastry = _has(n, SWEET + ["кроасан", "баничк", "тутманик", "кифл", "земел", "пекарна", "пица", "хотдог", "сандвич", "пита "])
    if not household and (explicit_lent or (_has(n, LENT) and not _has(n, ANIMAL) and not pastry)):
        tags.append("постни")
    if not household and _has(n, PRODUCE) and not _has(n, ANIMAL) and not _has(n, DRINKS + SWEET):
        tags.append("плодове")
    if not household and _has(n, DRINKS) and not dairy:
        tags.append("напитки")
    if not household and _has(n, BREAD):
        tags.append("хляб")
    if not household and _has(n, SWEET):
        tags.append("сладко")
    return tags


def tags_to_str(tags: list[str]) -> str:
    return ",".join(dict.fromkeys(tags))
